/**
 * CONTORNOS DE TALLER
 *
 * Sale de los DXF, no de proporciones inventadas: cada arreglo es el
 * contorno real de la pieza normalizado a 0..1 sobre su propio bbox, para
 * que escale con la medida que pida el producto.
 *
 * Generado de los DXF de referencia. Al cambiar un DXF hay que regenerarlo.
 */

/** Lleva un contorno normalizado a milímetros. */
export function escala(perfil: Punto2[], u: number, v: number): Punto2[] {
  return perfil.map(([a, b]) => [a * u, b * v] as Punto2);
}

